import fs from 'fs';
import path from 'path';
import { fileURLToPath } from 'url';

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const root = path.join(__dirname, '..');

// Read API key from .env without any external dependency
const envContent = fs.readFileSync(path.join(root, '.env'), 'utf-8');
const API_KEY = envContent.match(/ELEVENLABS_API_KEY=([^\r\n]+)/)?.[1]?.trim();
if (!API_KEY) throw new Error('ELEVENLABS_API_KEY not found in .env');

const VOICE_ID = 'pNInz6obpgDQGcFmaJgB'; // Adam — warm, clear narrator
const MODEL   = 'eleven_multilingual_v2';
const FPS     = 30;

const STEPS = [
  {
    id: 1, key: 'attention',
    text: `Step 1. Attention.

Making money online doesn't start with money. It starts with attention. At the beginning, you create content — videos, posts, or ideas — that people want to watch. No audience, no business. Everything begins here.`,
  },
  {
    id: 2, key: 'trust',
    text: `Step 2. Trust.

As people discover your content, something begins to change. They come back, they watch more, and over time, they start to trust you. You're no longer just another creator — you become someone they listen to.`,
  },
  {
    id: 3, key: 'offer',
    text: `Step 3. Offer.

And that's where the opportunity begins. You introduce something — a product, a service, or a tool. Not randomly, but in a way that connects with what your audience already cares about.`,
  },
  {
    id: 4, key: 'conversion',
    text: `Step 4. Conversion.

The goal isn't just to sell. It's to solve a problem. And when the right people see the value, some of them decide to buy. That's the moment attention turns into income.`,
  },
  {
    id: 5, key: 'scale',
    text: `Step 5. Scale.

Then everything expands. You create more content, improve your systems, and reach more people. Over time, the process becomes smoother, more predictable — until it starts working without you.`,
  },
];

async function generate(step) {
  process.stdout.write(`  Step ${step.id}  (${step.key}) ... `);

  const res = await fetch(`https://api.elevenlabs.io/v1/text-to-speech/${VOICE_ID}`, {
    method: 'POST',
    headers: { 'xi-api-key': API_KEY, 'Content-Type': 'application/json' },
    body: JSON.stringify({
      text: step.text,
      model_id: MODEL,
      voice_settings: { stability: 0.5, similarity_boost: 0.8, style: 0.1, use_speaker_boost: true },
    }),
  });

  if (!res.ok) throw new Error(`ElevenLabs ${res.status}: ${await res.text()}`);

  const buf = Buffer.from(await res.arrayBuffer());
  const outPath = path.join(root, 'public', `vo-${step.id}-${step.key}.mp3`);
  fs.writeFileSync(outPath, buf);
  process.stdout.write(`${Math.round(buf.length / 1024)} KB\n`);
  return buf.length;
}

// ─────────────────────────────────────────────────────────────────────────────
console.log('Calling ElevenLabs API...\n');
const sizes = [];
for (const step of STEPS) {
  sizes.push(await generate(step));
  if (step.id < STEPS.length) await new Promise(r => setTimeout(r, 700));
}

// Duration estimate: 128 kbps MP3 → 16 000 bytes/s
// Add 10 % padding so content holds long enough
const durSecs = sizes.map(sz => Math.round((sz / 16000) * 1.1 * 10) / 10);

const startFrames = durSecs.reduce((acc, d, i) => {
  acc.push(i === 0 ? 0 : acc[i - 1] + Math.round(durSecs[i - 1] * FPS));
  return acc;
}, []);

const finalSceneFrame = startFrames[4] + Math.round(durSecs[4] * FPS);
const totalFrames     = finalSceneFrame + Math.round(6 * FPS); // 6 s final scene

// Write timing constants used by the Remotion composition
const ts = `// Auto-generated by scripts/generate-voiceover.mjs — do not edit manually.
export const FPS = ${FPS};
export const STEP_START_FRAMES: number[] = [${startFrames.join(', ')}];
export const STEP_DURATIONS_S: number[]  = [${durSecs.join(', ')}];
export const FINAL_SCENE_FRAME = ${finalSceneFrame};
export const TOTAL_FRAMES = ${totalFrames};
`;

fs.writeFileSync(path.join(root, 'src', 'voTimings.ts'), ts);

console.log('\n--- Timing ---');
STEPS.forEach((s, i) => {
  const end = startFrames[i] / FPS + durSecs[i];
  console.log(`  Step ${s.id}: ${(startFrames[i] / FPS).toFixed(1)}s – ${end.toFixed(1)}s`);
});
console.log(`  Final:  ${(finalSceneFrame / FPS).toFixed(1)}s – ${(totalFrames / FPS).toFixed(1)}s`);
console.log(`\n  Total: ${(totalFrames / FPS).toFixed(1)} s  (${totalFrames} frames @ ${FPS} fps)`);
console.log('\n✓  src/voTimings.ts written');
